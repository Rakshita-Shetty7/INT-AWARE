"""
Intent and Attack Stage Models and Taxonomies.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class IntentCategory(str, Enum):
    """
    Controlled internal taxonomy of attacker intent categories.
    """
    RECONNAISSANCE = "RECONNAISSANCE"
    DISCOVERY = "DISCOVERY"
    CREDENTIAL_ACCESS = "CREDENTIAL_ACCESS"
    EXECUTION = "EXECUTION"
    PRIVILEGE_ESCALATION = "PRIVILEGE_ESCALATION"
    PERSISTENCE = "PERSISTENCE"
    EXPLOITATION = "EXPLOITATION"
    EXFILTRATION = "EXFILTRATION"
    CLEANUP = "CLEANUP"
    OTHER = "OTHER"


class AttackStage(str, Enum):
    """
    MITRE ATT&CK aligned attack lifecycle stages.
    """
    INITIAL_ACCESS = "INITIAL_ACCESS"
    RECONNAISSANCE = "RECONNAISSANCE"
    DISCOVERY = "DISCOVERY"
    EXECUTION = "EXECUTION"
    CREDENTIAL_ACCESS = "CREDENTIAL_ACCESS"
    PRIVILEGE_ESCALATION = "PRIVILEGE_ESCALATION"
    PERSISTENCE = "PERSISTENCE"
    EXFILTRATION = "EXFILTRATION"
    CLEANUP = "CLEANUP"
    UNKNOWN = "UNKNOWN"


class ClassificationSource(str, Enum):
    """
    Provenance of the classification decision.
    """
    RULE = "RULE"
    ML = "ML"
    GEMINI = "GEMINI"
    HYBRID = "HYBRID"
    FALLBACK = "FALLBACK"


class RuleClassification(BaseModel):
    """
    Result emitted by the deterministic Rule Engine.
    """
    model_config = ConfigDict(use_enum_values=True)

    intent: IntentCategory = Field(..., description="Classified intent category")
    attack_stage: AttackStage = Field(..., description="Estimated attack stage")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0")
    rule_matches: List[str] = Field(default_factory=list, description="IDs or names of triggered rules")
    evidence: List[str] = Field(default_factory=list, description="Transparent explanations of why rules fired")


class GeminiClassification(BaseModel):
    """
    Structured response schema requested from and validated against Google Gemini LLM.
    """
    model_config = ConfigDict(use_enum_values=True)

    intent: IntentCategory = Field(..., description="Classified intent category")
    attack_stage: AttackStage = Field(..., description="Estimated attack stage")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0")
    reason: str = Field(..., description="Explanation of why this intent and stage were determined")
    evidence: List[str] = Field(default_factory=list, description="Key behavioral markers supporting classification")


class MLClassification(BaseModel):
    """
    Result emitted by the trained ML intent classifier (command -> intent).

    ``top_predictions`` exposes the model's ranked alternatives so the decision is
    explainable rather than a bare label. Includes epistemic uncertainty metrics
    (entropy, novelty score, abstention recommendation) for out-of-distribution detection.
    """
    model_config = ConfigDict(use_enum_values=True)

    intent: IntentCategory = Field(..., description="Predicted intent category")
    attack_stage: AttackStage = Field(..., description="Attack stage mapped from the predicted intent")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Calibrated probability of the top class")
    model_name: str = Field(..., description="Name of the deployed model that produced this prediction")
    top_predictions: List[dict] = Field(
        default_factory=list,
        description="Ranked [{intent, probability}] alternatives for explainability",
    )
    evidence: List[str] = Field(default_factory=list, description="Human-readable explanation of the ML decision")
    entropy: float = Field(0.0, ge=0.0, description="Shannon prediction entropy across intent classes (in bits)")
    novelty_score: float = Field(0.0, ge=0.0, le=1.0, description="Out-of-distribution novelty score (0.0=in-dist, 1.0=unseen/anomalous)")
    is_novel: bool = Field(False, description="Flag indicating out-of-distribution or unseen command pattern")
    should_abstain: bool = Field(False, description="Whether the classifier recommends abstaining due to high uncertainty")


class HybridClassification(BaseModel):
    """
    Unified classification decision consolidating Rule Engine, ML model and Gemini LLM outputs.
    """
    model_config = ConfigDict(use_enum_values=True)

    intent: IntentCategory = Field(..., description="Final resolved intent category")
    attack_stage: AttackStage = Field(..., description="Final resolved attack stage")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Resolved confidence score")
    source: ClassificationSource = Field(..., description="Classification provenance")
    rule_evidence: List[str] = Field(default_factory=list, description="Evidence generated by Rule Engine")
    ml_intent: Optional[IntentCategory] = Field(None, description="Intent predicted by the ML model (if available)")
    ml_confidence: Optional[float] = Field(None, description="ML model calibrated confidence (if available)")
    ml_model_name: Optional[str] = Field(None, description="Name of the ML model that produced ml_intent")
    ml_evidence: List[str] = Field(default_factory=list, description="Explanation from the ML model")
    ai_reason: Optional[str] = Field(None, description="Explanation provided by Gemini AI")
    ai_evidence: List[str] = Field(default_factory=list, description="Key markers identified by Gemini AI")
    uncertainty_score: float = Field(0.0, ge=0.0, le=1.0, description="Epistemic uncertainty score of the consolidated classification")
    is_novel: bool = Field(False, description="Whether the command is flagged as out-of-distribution/novel")
    should_abstain: bool = Field(False, description="Whether the system recommends human/escalated analyst review")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="UTC timestamp of classification")
